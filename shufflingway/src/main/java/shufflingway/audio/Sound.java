package shufflingway.audio;

/**
 * Every sound effect the app plays, each keyed to a file under {@code /sounds/} on the classpath
 * ({@code src/main/resources/sounds/}). Play one with {@link SoundEffects#play(Sound)}.
 *
 * <p>Files must be PCM WAV (8- or 16-bit, any common rate), which Java Sound decodes without
 * extra libraries. Keep a short tail of silence after the audible part: some mixers drop a clip
 * that ends within a few milliseconds of starting.
 */
public enum Sound {

	/**
	 * A short UI click, the app's one sound for a button clicked: the Auto / Wait toggle, the
	 * LIMIT and RFP buttons, a field card's action buttons.
	 */
	TICK("tick.wav"),

	/** {@link #CHAT_RECEIVE} inverted, a fifth down: a multiplayer chat message you sent. */
	CHAT_SEND("chat_send.wav"),

	/** A two-note blip, a fifth up: a multiplayer chat message from the opponent. */
	CHAT_RECEIVE("chat_receive.wav"),

	/**
	 * A soft rising bell arpeggio on {@link #CHAT_RECEIVE}'s A (A5, C♯6, E6): an opponent has
	 * connected to the lobby you are hosting. Generated by {@code tools/sounds/make_lobby_chime.py}.
	 */
	LOBBY_JOIN("lobby_join.wav"),

	/**
	 * A card set down on the board, as it comes to rest in its slot: a soft, dull tap with a faint
	 * paper edge, about 10 dB under the deck tapped down at the end of {@link #SHUFFLE}, since it is
	 * heard with every card played. Generated by {@code tools/sounds/make_card_place.py}; the
	 * candidates are in {@code make_card_place_samples.py}.
	 */
	CARD_PLACE("card_place.wav"),

	/**
	 * A deck riffled and set down: a cut sliding off, a flutter of card edges, then the shuffled
	 * deck pushed back and tapped down. Timed to {@code DeckShuffleAnimator}'s phases. Generated by
	 * {@code tools/sounds/make_shuffle.py}; the candidates are in {@code make_shuffle_samples.py}.
	 */
	SHUFFLE("shuffle.wav");

	final String file;

	Sound(String file) {
		this.file = file;
	}

	String resourcePath() {
		return "/sounds/" + file;
	}
}
